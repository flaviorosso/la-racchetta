function buildWhatsAppUrl(message) {
  return `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(message)}`;
}

function applyLanguage(lang) {
  const t = translations[lang] || translations.de;
  document.documentElement.lang = lang;
  document.title = t.page_title;
  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.setAttribute("content", t.meta_description);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (t[key] !== undefined) el.innerHTML = t[key];
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const key = el.dataset.i18nAlt;
    if (t[key] !== undefined) el.setAttribute("alt", t[key]);
  });

  document.querySelectorAll(".js-whatsapp").forEach((link) => {
    const message = lang === "pt" ? (link.dataset.messagePt || link.dataset.messageDe || "") : (link.dataset.messageDe || link.dataset.messagePt || "");
    link.href = buildWhatsAppUrl(message);
    link.target = "_blank";
    link.rel = "noopener";
  });

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });

  localStorage.setItem("laracchetta_lang", lang);
}

const savedLang = localStorage.getItem("laracchetta_lang") || "de";
applyLanguage(savedLang);

document.querySelectorAll(".lang-btn").forEach((btn) => {
  btn.addEventListener("click", () => applyLanguage(btn.dataset.lang));
});
